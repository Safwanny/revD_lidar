"""
Write worlds/house.sdf: a 20 x 15 m house for mapping and localization.

Plan (x east, y north, origin at the house centre, walls 0.1 m thick):

    +-----------+-----------+-----------+------------------+
    |           | bedroom A | bedroom B |                  |
    |  living   |  (twins: same size, bed  |    kitchen   |
    |  room     |   and wardrobe spot)     |   + dining    |
    |           +--d--------+--d--------+                  |
    |           d  corridor 7 x 1.2 m   d                  |
    |           +--d--------+---d-------+                  |
    |           |  bathroom |  office   |                  |
    +-----------+-----------+-----------+------------------+

Doorways (d) are 0.7-0.9 m. Furniture stands on the floor or on thin legs
the scan plane (85 mm) cuts: no drops, no overhangs below the deck.
Run from the package root; the SDF is committed and test_worlds.py checks it
matches this script.
"""

import math
from pathlib import Path
import sys

WALL_THICKNESS = 0.1
WALL_HEIGHT = 1.0
X0, X1, Y0, Y1 = -10.0, 10.0, -7.5, 7.5
CORRIDOR = (-4.0, 3.0, -0.6, 0.6)  # x0, x1, y0, y1: 7 m long

WOOD = '0.55 0.35 0.20 1'
FABRIC = '0.30 0.35 0.55 1'
WALL = '0.85 0.85 0.80 1'

HEADER = """<?xml version="1.0"?>
<!-- Generated by scripts/generate_house.py; edit the script, not this file. -->
<sdf version="1.9">
  <world name="house">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <light type="directional" name="sun">
      <pose>0 0 10 0 0 0</pose><cast_shadows>true</cast_shadows>
      <diffuse>0.85 0.85 0.85 1</diffuse><specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>24 19</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>24 19</size></plane></geometry>
          <material>
            <ambient>0.60 0.60 0.60 1</ambient><diffuse>0.60 0.60 0.60 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
"""


def fmt(*values):
    return ' '.join(f'{v:.4g}' for v in values)


def model(name, x, y, z, yaw, geometry, colour):
    return f"""    <model name="{name}">
      <static>true</static><pose>{fmt(x, y, z, 0, 0, yaw)}</pose>
      <link name="link">
        <collision name="collision"><geometry>{geometry}</geometry></collision>
        <visual name="visual"><geometry>{geometry}</geometry>
          <material><ambient>{colour}</ambient><diffuse>{colour}</diffuse></material></visual>
      </link>
    </model>
"""


def box(name, x, y, z, sx, sy, sz, colour, yaw=0.0):
    return model(name, x, y, z, yaw,
                 f'<box><size>{fmt(sx, sy, sz)}</size></box>', colour)


def leg(name, x, y, height, radius):
    return model(name, x, y, height / 2, 0.0,
                 f'<cylinder><radius>{radius}</radius>'
                 f'<length>{fmt(height)}</length></cylinder>', WOOD)


def wall(name, a, b, doors=()):
    """
    Wall from a to b (axis-aligned), cut by (centre, width) doorways.

    Centres are measured along the wall from a.
    """
    length = math.dist(a, b)
    ux, uy = (b[0] - a[0]) / length, (b[1] - a[1]) / length
    cuts = [0.0]
    for centre, width in sorted(doors):
        cuts += [centre - width / 2, centre + width / 2]
    cuts.append(length)
    out = ''
    for i, (s0, s1) in enumerate(zip(cuts[::2], cuts[1::2])):
        if s1 - s0 < 1e-6:
            continue
        mid = (s0 + s1) / 2
        # Pieces overlap by half a thickness at each end so corners close.
        size = s1 - s0 + WALL_THICKNESS
        sx, sy = (size, WALL_THICKNESS) if abs(ux) > 0.5 else (WALL_THICKNESS, size)
        out += box(f'{name}_{i}', a[0] + ux * mid, a[1] + uy * mid,
                   WALL_HEIGHT / 2, sx, sy, WALL_HEIGHT, WALL)
    return out


def table(name, x, y, sx, sy, height=0.72, leg_radius=0.02, yaw=0.0):
    """Top on four thin legs: the scan plane sees only the legs."""
    out = box(f'{name}_top', x, y, height - 0.015, sx, sy, 0.03, WOOD, yaw)
    c, s = math.cos(yaw), math.sin(yaw)
    for i, (dx, dy) in enumerate([(1, 1), (1, -1), (-1, 1), (-1, -1)]):
        lx, ly = dx * (sx / 2 - 0.05), dy * (sy / 2 - 0.05)
        out += leg(f'{name}_leg{i}', x + c * lx - s * ly, y + s * lx + c * ly,
                   height - 0.03, leg_radius)
    return out


def bedroom(name, x0):
    """
    Furnish a 3.5 x 6.9 m bedroom north of the corridor, west wall at x0.

    Both bedrooms call this with the same offsets, so they look alike to the
    LiDAR: the symmetric pair for AMCL.
    """
    return (box(f'{name}_bed', x0 + 1.75, 6.45, 0.25, 1.6, 2.0, 0.5, FABRIC)
            + box(f'{name}_wardrobe', x0 + 0.35, 3.0, 0.9, 0.6, 1.2, 1.8, WOOD)
            + table(f'{name}_desk', x0 + 2.9, 2.0, 0.6, 1.2, height=0.75))


def house():
    cx0, cx1, cy0, cy1 = CORRIDOR
    parts = [HEADER]
    # Outer shell.
    parts.append(wall('outer_south', (X0, Y0), (X1, Y0)))
    parts.append(wall('outer_north', (X0, Y1), (X1, Y1)))
    parts.append(wall('outer_west', (X0, Y0), (X0, Y1)))
    parts.append(wall('outer_east', (X1, Y0), (X1, Y1)))
    # Living room | corridor block | kitchen, each with a doorway onto the
    # corridor. Blocks run the full depth north and south of the corridor.
    parts.append(wall('living_east_south', (cx0, Y0), (cx0, cy0)))
    parts.append(wall('living_east_corridor', (cx0, cy0), (cx0, cy1),
                      doors=[(0.6, 0.9)]))
    parts.append(wall('living_east_north', (cx0, cy1), (cx0, Y1)))
    parts.append(wall('kitchen_west_south', (cx1, Y0), (cx1, cy0)))
    parts.append(wall('kitchen_west_corridor', (cx1, cy0), (cx1, cy1),
                      doors=[(0.6, 0.8)]))
    parts.append(wall('kitchen_west_north', (cx1, cy1), (cx1, Y1)))
    # Corridor walls with the bedroom doors (north), bathroom and office
    # doors (south). Bedroom doors sit at the same offset in each room.
    mid_north = (cx0 + cx1) / 2
    parts.append(wall('corridor_north', (cx0, cy1), (cx1, cy1),
                      doors=[(1.0, 0.8), (mid_north - cx0 + 1.0, 0.8)]))
    parts.append(wall('corridor_south', (cx0, cy0), (cx1, cy0),
                      doors=[(2.0, 0.7), (5.5, 0.75)]))
    parts.append(wall('bedroom_split', (mid_north, cy1), (mid_north, Y1)))
    parts.append(wall('bath_split', (0.0, Y0), (0.0, cy0)))
    # Kitchen / dining divider: a 1 m opening in front of the corridor door
    # and open at the east end.
    parts.append(wall('dining_divider', (cx1, 0.0), (8.5, 0.0),
                      doors=[(0.5, 1.0)]))

    # Living room: sofa and armchair on the floor, coffee table on legs.
    parts.append(box('sofa', -9.45, 2.0, 0.4, 0.9, 2.2, 0.8, FABRIC))
    parts.append(box('armchair', -6.2, 4.5, 0.4, 0.8, 0.8, 0.8, FABRIC,
                     yaw=0.5))
    parts.append(table('coffee_table', -7.6, 2.0, 0.6, 1.1, height=0.45,
                       leg_radius=0.015))
    parts.append(box('tv_stand', -4.35, 4.5, 0.25, 0.5, 1.6, 0.5, WOOD))
    parts.append(box('bookshelf', -7.0, -7.2, 0.9, 2.0, 0.4, 1.8, WOOD))
    parts.append(table('side_table', -9.3, -4.0, 0.6, 0.6, height=0.6,
                       leg_radius=0.015))
    # The bedroom pair.
    parts.append(bedroom('bedroom_a', cx0))
    parts.append(bedroom('bedroom_b', mid_north))
    # Bathroom and office.
    parts.append(box('bathtub', -3.15, -6.65, 0.3, 1.6, 1.6, 0.6, WALL))
    parts.append(box('vanity', -0.4, -3.0, 0.4, 0.6, 1.0, 0.8, WOOD))
    parts.append(table('office_desk', 1.5, -6.95, 1.4, 0.7, height=0.75))
    parts.append(box('filing_cabinet', 2.6, -3.0, 0.5, 0.5, 0.5, 1.0, WOOD))
    # Kitchen (north of the divider): counters along two walls, island.
    parts.append(box('counter_north', 6.5, 7.15, 0.45, 6.8, 0.6, 0.9, WOOD))
    parts.append(box('counter_east', 9.65, 4.0, 0.45, 0.6, 3.6, 0.9, WOOD))
    parts.append(box('island', 6.5, 3.8, 0.45, 2.0, 0.9, 0.9, WOOD))
    # Dining (south): table on legs, four chairs on thin legs.
    parts.append(table('dining_table', 6.5, -4.0, 1.6, 0.9))
    for i, (x, y) in enumerate([(5.9, -3.2), (7.1, -3.2),
                                (5.9, -4.8), (7.1, -4.8)]):
        parts.append(table(f'chair{i}', x, y, 0.42, 0.42, height=0.45,
                           leg_radius=0.012))
    parts.append(box('sideboard', 9.7, -5.0, 0.4, 0.5, 1.8, 0.8, WOOD))
    parts.append('  </world>\n</sdf>\n')
    return ''.join(parts)


if __name__ == '__main__':
    out = Path(sys.argv[1] if len(sys.argv) > 1 else 'worlds/house.sdf')
    out.write_text(house(), encoding='utf-8')
